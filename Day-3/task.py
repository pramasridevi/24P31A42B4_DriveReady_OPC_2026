import os
from google.colab import userdata
os.environ["FRIST_OPENAPI"]=userdata.get("FRIST_OPENAPI")
from langchain_groq import ChatGroq
llm=ChatGroq(model="openai/gpt-oss-120b",temperature=0.1)

from langchain_core.prompts import ChatPromptTemplate,MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE:   You are the friendly shopping assistant for Kiran Shop.
FACTS:  Help customers with product details, prices, availability, and quantities.
        Calculate the total price accurately based on quantity.
        Recommend suitable products based on customer requirements.
        Tea Powder is avaliable
RULES:
            1. Understand spelling mistakes like teapowder, poder and grogeryies.
            2. For price questions, mention the product and price enquiry.
            3. For availability questions, clearly answer about grocery availability.
            4. For order questions, id   entify the product and requested time.
            5. For delivery questions, mention the customer's location.
            6. For quantity questions, identify both product and quantity.
            7. Never invent prices or availability.
            8. Give short and direct answers.
            9.Tea Powder cost is 75
            10.the order can delievery take the 24 hours
            11.the 6 packet milk is 120
            12.they are soaps are avaliable
FORMAT: Under 50 words, friendly, English or Telugu matching the customer."""

prompt=ChatPromptTemplate.from_messages([
    ("system",SYSTEM),
    MessagesPlaceholder("history"),
    ("human","{question}"),
])
chain=prompt | llm | StrOutputParser()
history =[]
def ask(question:str)->str:
  answer=chain.invoke({"history": history,"question":question})
  history.extend([("human",question),("ai",answer)])
  return answer
print(ask("Hi I'm rama.do you have teapowder"))
print(ask("what is your name"))

